def test_a_pool_leg_is_a_typed_party_and_the_correspondence_resolves(run: Any) -> None:
    """The liquidity pool of a leg (ScAddress type 4) is a typed
    counterparty, not an account and not its liquidity providers. The leg is kept, so the
    correspondence of A's debit resolves (until increment 3 it stayed sac_incomplete)."""
    store, _, sac = run
    effects = _effects(store, "pp-pool")
    assert sorted(effects) == ["0:classic:debit", "0:sac:0"]
    leg = effects["0:sac:0"]
    assert (leg.account, leg.direction) == (A, "debit")
    assert leg.counterparty is not None and leg.counterparty.kind == "liquidity_pool"
    assert leg.counterparty.id is not None and leg.counterparty.id.startswith("L")
    check = _correspondence(store, "pp-pool")
    assert check["status"] == "corroborated" and check["sac_net"][A] == "-30000000"
    assert not [e for e in sac.exclusions if e.reason == "UNSUPPORTED_PARTY"]


def test_undecodable_leg_party_leaves_the_correspondence_incomplete(run: Any) -> None:
    """A leg party that is no typed party, derived from the synthetic pool leg: a muxed
    account (ScAddress type 2, which CAP-67 never puts in the topics; decoded since
    increment 4, so its M address and the base account are named) or an unknown address
    type (its parties unknown). The leg is not kept and the operation's correspondence stays
    incomplete."""
    store, _, _ = run
    leg = next(
        o for o in store.observations() if o.source.record_key == f"{_tx('pp-pool')}:0:sac:0"
    )
    raw = (store.root / "pages" / f"{leg.provenance.raw_sha256}.json").read_bytes()
    page = Page("synthetic#pp-pool", raw, leg.provenance.raw_sha256, json.loads(raw))
    event = copy.deepcopy(
        next(e for e in page.document["result"]["events"] if e["txHash"] == _tx("pp-pool"))
    )
    muxed = struct.pack(">iiQ", 18, 2, 7) + b"\x01" * 32
    event["topic"][2] = base64.b64encode(muxed).decode()
    operation = next(e for e in store.path_operations() if e["tx_hash"] == _tx("pp-pool"))
    (party,) = normalize_sac_leg(TARGET, event, 0, operation, page, RECORDED_AT)
    assert isinstance(party, Exclusion) and party.reason == "UNSUPPORTED_PARTY"
    m_address = encode_muxed_account(encode_account_id(b"\x01" * 32), 7)
    assert party.quarantine and party.addresses is not None and m_address in party.addresses
    assert party.operation == _op("pp-pool")
    event["topic"][2] = base64.b64encode(struct.pack(">ii", 18, 9) + b"\x01" * 32).decode()
    (unknown,) = normalize_sac_leg(TARGET, event, 0, operation, page, RECORDED_AT)
    assert isinstance(unknown, Exclusion) and unknown.reason == "UNSUPPORTED_PARTY"
    assert unknown.addresses is None
    assert path_correspondence(operation, [], True)["status"] == "sac_incomplete"



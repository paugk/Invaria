ROOT = Path(__file__).resolve().parents[1] / "fixtures"
SYNTHETIC = ROOT / "stellar/synthetic/dex-fills"
START, END = 90000200, 90000215
RECORDED_AT = datetime(2026, 10, 7, 10, 0, tzinfo=UTC)
TARGET = parse_contract(ChainTarget, (SYNTHETIC / "target.json").read_text("utf-8"))
A = TARGET.account
HORIZON_URL, RPC_URL = "https://horizon.synthetic.invalid", "https://rpc.synthetic.invalid"


def _account(label: str) -> str:
    raw = hashlib.sha256(f"invaria:synthetic:stellar:account:{label}".encode()).digest()
    return encode_account_id(raw)


def _tx(label: str) -> str:
    return hashlib.sha256(f"invaria:synthetic:stellar:tx:dex:{label}".encode()).hexdigest()


P1, P3, O1, E = (
    _account(x) for x in ("dex-taker-1", "dex-taker-3", "dex-offer-owner-1", "dex-payer")
)


@pytest.fixture(autouse=True)
def no_network(monkeypatch: pytest.MonkeyPatch) -> None:
    def blocked(*_: Any, **__: Any) -> Any:
        raise AssertionError("network access attempted in an offline test")

    monkeypatch.setattr(socket, "socket", blocked)
    monkeypatch.setattr(socket, "create_connection", blocked)
    monkeypatch.setattr(socket, "getaddrinfo", blocked)


def _clients() -> tuple[Horizon, Rpc]:
    client = ReplayClient(SYNTHETIC / "recordings")
    return Horizon(HORIZON_URL, client), Rpc(RPC_URL, client)


def _ingest(store: IngestStore) -> tuple[RunResult, RunResult]:
    horizon, rpc = _clients()
    check = verify_network(horizon, rpc, "stellar:testnet")
    classic = ingest_horizon_payments(
        TARGET,
        horizon,
        store,
        start_ledger=START,
        end_ledger=END,
        history=(check.horizon_elder_ledger, check.horizon_latest_ledger),
        recorded_at=RECORDED_AT,
    )
    sac = ingest_sac_events(
        TARGET, rpc, horizon, store, start_ledger=START, end_ledger=END, recorded_at=RECORDED_AT
    )
    return classic, sac


@pytest.fixture(scope="module")
def run(tmp_path_factory: pytest.TempPathFactory) -> tuple[IngestStore, RunResult, RunResult]:
    store = IngestStore(tmp_path_factory.mktemp("dex"))
    classic, sac = _ingest(store)  # ReplayClient never opens a socket
    return store, classic, sac


def _of(store: IngestStore, label: str) -> list[Observation]:
    return [o for o in store.observations() if o.source.record_key.startswith(_tx(label))]


def _payload(observation: Observation) -> ChainEffectPayload:
    assert isinstance(observation.payload, ChainEffectPayload)
    return observation.payload


def _status(store: IngestStore, label: str) -> str:
    return str(store.current_correspondence()[(TARGET.target_id, _tx(label), 0)]["status"])


def test_the_fixture_is_marked_synthetic() -> None:
    assert TARGET.synthetic and HORIZON_URL.endswith(".invalid") and START > 50_000_000
    for meta in (SYNTHETIC / "recordings").glob("*.json"):
        assert "SYNTHETIC" in json.loads(meta.read_text("utf-8"))["synthetic"]


def test_a_fill_of_the_watched_offer_is_an_exchange_effect(run: Any) -> None:
    """P1's path payment crosses A's offer: the fill is A's effect, not P1's payment."""
    store, _, _ = run
    effects = _of(store, "fill-maker-path")
    assert [o.fact_type for o in effects] == ["chain_effect", "chain_effect"]
    classic, sac = sorted(effects, key=lambda o: _payload(o).representation)
    for observation in (classic, sac):
        payload = _payload(observation)
        assert (payload.effect_kind, payload.account, payload.direction) == (
            "dex_fill",
            A,
            "debit",
        )
        assert payload.units is not None and payload.units.atoms == "30000000"
        assert payload.counterparty is not None and payload.counterparty.id == P1
        assert payload.exchange is not None
        assert (payload.exchange.operation_type, payload.exchange.operation_source) == (
            "path_payment_strict_send",
            P1,
        )
        assert observation.operation_ref is None
    trade = _payload(classic).exchange
    assert trade is not None and trade.offer_id == "7001"
    assert (trade.sold_amount, trade.bought_amount) == ("30000000", "33000000")
    assert trade.sold_asset is not None and trade.sold_asset.startswith("SYNUSD:")
    assert trade.bought_asset is not None and trade.bought_asset.startswith("EURX:")
    # Nothing is attributed to the submitter, and the event between P1 and B is not A's.
    assert all(_payload(o).account == A for o in effects)
    assert _status(store, "fill-maker-path") == "corroborated"



def _tx(label: str) -> str:
    return hashlib.sha256(f"invaria:synthetic:stellar:tx:{label}".encode()).hexdigest()


def _account(label: str) -> str:
    raw = hashlib.sha256(f"invaria:synthetic:stellar:account:{label}".encode()).digest()
    return encode_account_id(raw)


B, C, D, E = (_account(x) for x in ("b", "c", "d", "e"))
O1, O2 = _account("offer-owner-1"), _account("offer-owner-2")


def _effects(store: IngestStore, label: str) -> dict[str, ChainEffectPayload]:
    """Chain effects of one synthetic transaction, by record key suffix after the tx hash."""
    found: dict[str, ChainEffectPayload] = {}
    for o in store.observations():
        if o.source.record_key.startswith(_tx(label)) and isinstance(o.payload, ChainEffectPayload):
            found[o.source.record_key[65:]] = o.payload
    return found


def _correspondence(store: IngestStore, label: str, op_index: int = 0) -> dict[str, Any]:
    (entry,) = [
        e for e in store.correspondence() if (e["tx_hash"], e["op_index"]) == (_tx(label), op_index)
    ]
    return entry


def _op(label: str, op_index: int = 0) -> str:
    return f"{_tx(label)}:{op_index}@SYNUSD:{TARGET.asset_issuer}"


def _exclusions(result: RunResult, reason: str) -> list[Exclusion]:
    return [e for e in result.exclusions if e.reason == reason]



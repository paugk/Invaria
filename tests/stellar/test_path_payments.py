class _ShortScanRpc(Rpc):
    """RPC that returns short pages whose cursor shows it did not scan to the end."""

    def __init__(self) -> None:
        super().__init__(RPC_URL, ReplayClient(SYNTHETIC / "recordings"))
        self.calls = 0

    def get_events(self, contract_id: str, **_: Any) -> Page:
        self.calls += 1
        document = {
            "jsonrpc": "2.0",
            "id": 1,
            "result": {
                "events": [],
                "latestLedger": END + 90,
                "cursor": f"{((START + 2) << 32) - 1:019d}-4294967295",
            },
        }
        raw = json.dumps(document).encode()
        return Page(f"rpc:short#{self.calls}", raw, hashlib.sha256(raw).hexdigest(), document)



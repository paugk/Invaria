def test_fill_correspondence_rules(run: Any) -> None:
    store, _, _ = run
    classic, sac = sorted(_of(store, "fill-maker-path"), key=lambda o: _payload(o).representation)
    operation = (_tx("fill-maker-path"), 0, START + 1)
    assert fill_correspondence(TARGET, operation, [classic], [sac], False)["status"] == (
        "corroborated"
    )
    assert fill_correspondence(TARGET, operation, [classic], [sac], True)["status"] == (
        "sac_incomplete"
    )
    assert fill_correspondence(TARGET, operation, [], [sac], False)["status"] == "sac_only"
    # Same net, different gross: a debit and a credit of 3 never equal one of 0.
    payload = _payload(sac)
    assert payload.units is not None
    reverse = sac.model_copy(
        update={
            "observation_id": "obs-reverse",
            "payload": payload.model_copy(update={"direction": "credit"}),
        }
    )
    twin = sac.model_copy(update={"observation_id": "obs-twin"})
    record = fill_correspondence(TARGET, operation, [classic], [sac, twin, reverse], False)
    assert record["classic_net"] == record["sac_net"]
    assert record["status"] == "conflict"


def test_two_contents_for_one_fill_leave_it_incomplete(tmp_path: Path) -> None:
    store = IngestStore(tmp_path)
    _ingest(store)
    key = (TARGET.target_id, _tx("fill-maker-path"), 0)
    assert store.current_correspondence()[key]["status"] == "corroborated"
    sac = next(o for o in _of(store, "fill-maker-path") if _payload(o).representation == "sac")
    units = _payload(sac).units
    assert units is not None
    altered = sac.model_copy(
        update={
            "observation_id": "obs-altered-fill",
            "payload": _payload(sac).model_copy(
                update={"units": units.model_copy(update={"atoms": "1"})}
            ),
        }
    )
    store.append_observations([altered])
    _ingest(store)
    assert store.current_correspondence()[key]["status"] == "sac_incomplete"


def test_a_record_on_a_linked_operation_lists_the_link_and_keeps_its_addresses(
    tmp_path: Path,
) -> None:
    """An operation an ExecutionLink names cannot be scoped away by its addresses: its
    records list the linked operation, and their known addresses are kept."""
    link = ExecutionLink(
        schema_version="1.0",
        network="stellar:testnet",
        tx_hash=_tx("fill-conflict"),
        operation_index=0,
        ordinal=0,
        operation_ref="SYN-OP-0001",
        approval_ref="approval-synthetic-test",
        recorded_at=RECORDED_AT,
    )
    store = IngestStore(tmp_path)
    horizon, rpc = _clients()
    check = verify_network(horizon, rpc, "stellar:testnet")
    ingest_horizon_payments(
        TARGET,
        horizon,
        store,
        start_ledger=START,
        end_ledger=END,
        history=(check.horizon_elder_ledger, check.horizon_latest_ledger),
        recorded_at=RECORDED_AT,
        links=[link],
    )
    sac = ingest_sac_events(
        TARGET,
        rpc,
        horizon,
        store,
        start_ledger=START,
        end_ledger=END,
        recorded_at=RECORDED_AT,
        links=[link],
    )
    assert sac.coverage is not None and sac.coverage.quarantined_records is not None
    linked = [r for r in sac.coverage.quarantined_records if r.execution_links]
    # The fill event and the conflicting check of the linked operation.
    assert sorted(r.reasons[0] for r in linked) == [
        "CORRESPONDENCE_CONFLICT",
        "EFFECT_NOT_A_MOVEMENT",
    ]
    for record in linked:
        assert record.execution_links == ["SYN-OP-0001"]
        assert record.chain_operation == f"{_tx('fill-conflict')}:0"
        assert record.addresses is not None and len(record.addresses) >= 2
    # The same run without the link gives the same records, addresses included.
    store = IngestStore(tmp_path / "plain")
    ingest_horizon_payments(
        TARGET,
        horizon,
        store,
        start_ledger=START,
        end_ledger=END,
        history=(check.horizon_elder_ledger, check.horizon_latest_ledger),
        recorded_at=RECORDED_AT,
    )
    plain = ingest_sac_events(
        TARGET, rpc, horizon, store, start_ledger=START, end_ledger=END, recorded_at=RECORDED_AT
    )
    assert plain.coverage is not None and plain.coverage.quarantined_records is not None
    by_locator = {r.locator: r for r in plain.coverage.quarantined_records}
    for record in linked:
        if record.locator in by_locator:
            assert by_locator[record.locator].addresses == record.addresses
            assert by_locator[record.locator].execution_links is None


def test_two_targets_see_one_fill_from_their_own_side(tmp_path: Path) -> None:
    """A's manage offer crosses O1's offer: one SAC event, two perspectives, no collision,
    and each correspondence sums only its own account."""
    owner = parse_contract(ChainTarget, (SYNTHETIC / "target-offer-owner.json").read_text("utf-8"))
    store = IngestStore(tmp_path)
    _ingest(store)
    horizon, rpc = _clients()
    check = verify_network(horizon, rpc, "stellar:testnet")
    ingest_horizon_payments(
        owner,
        horizon,
        store,
        start_ledger=START,
        end_ledger=END,
        history=(check.horizon_elder_ledger, check.horizon_latest_ledger),
        recorded_at=RECORDED_AT,
    )
    second = ingest_sac_events(
        owner, rpc, horizon, store, start_ledger=START, end_ledger=END, recorded_at=RECORDED_AT
    )
    assert second.conflicts == ()
    effects = _of(store, "fill-taker-manage")
    sides = {
        (_payload(o).representation, _payload(o).account, _payload(o).direction) for o in effects
    }
    assert sides == {
        ("classic", A, "credit"),
        ("sac", A, "credit"),
        ("classic", O1, "debit"),
        ("sac", O1, "debit"),
    }
    assert len({o.source.record_key for o in effects}) == 4
    current = store.current_correspondence()
    mine = current[(TARGET.target_id, _tx("fill-taker-manage"), 0)]
    theirs = current[(owner.target_id, _tx("fill-taker-manage"), 0)]
    assert (mine["status"], mine["classic_net"]) == ("corroborated", {A: "20000000"})
    assert (theirs["status"], theirs["classic_net"]) == ("corroborated", {O1: "-20000000"})


class _OddHorizon(Horizon):
    """Horizon whose operations page has an unexpected shape."""

    def __init__(self) -> None:
        super().__init__(HORIZON_URL, ReplayClient(SYNTHETIC / "recordings"))

    def transaction_operations(self, tx_hash: str) -> Page:
        document = {"_synthetic": "test", "_embedded": {"records": [{"type": "payment"}]}}
        raw = json.dumps(document).encode()
        return Page("horizon:odd", raw, hashlib.sha256(raw).hexdigest(), document)


def test_an_odd_horizon_response_leaves_the_origin_unresolved() -> None:
    origin = _operation_origin(
        TARGET, _OddHorizon(), _tx("fill-maker-path"), 0, START + 1, RECORDED_AT
    )
    assert (origin.kind, origin.reason, origin.classic) == (
        "unresolved",
        "incomplete_trade_data",
        (),
    )

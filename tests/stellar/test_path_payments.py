def test_strict_send_debit_is_the_executed_source_amount(run: Any) -> None:
    store, _, _ = run
    effects = _effects(store, "pp-send-debit")
    debit = effects["0:classic:debit"]
    assert (debit.effect_kind, debit.account, debit.direction) == ("path_payment_debit", A, "debit")
    assert debit.units is not None and (debit.units.atoms, debit.units.unit) == (
        "100000000",
        "SYNUSD",
    )
    assert debit.counterparty == ChainParty(kind="account", id=B)
    context = debit.path_payment
    assert context is not None and context.operation_type == "path_payment_strict_send"
    # The destination side stays in its own asset, unconverted; destMin (9.0) is never read.
    assert context.destination_asset.startswith("EURX:")
    assert (context.source_amount, context.destination_amount) == ("100000000", "95000000")
    assert "0:classic:credit" not in effects  # EURX is not the watched asset
    assert debit.transaction is not None
    assert (debit.transaction.fee_account, debit.transaction.fee_charged.atoms) == (
        A,
        "100",
    )
    assert debit.transaction.fee_charged.unit == "XLM"


def test_strict_receive_credit_ignores_source_max_and_sums_legs(run: Any) -> None:
    store, _, _ = run

@pytest.mark.parametrize("corpus_name", ["subscription-synthetic", "redemption-synthetic"])
def test_engines_ignore_chain_effects_in_the_snapshot(run: Any, corpus_name: str) -> None:
    store, _, _ = run
    corpus = load_corpus(ROOT / "corpus" / corpus_name)
    sample = next(o for o in store.observations() if o.fact_type == "chain_effect")
    for scenario_id in sorted(corpus.scenarios):
        inputs = corpus.inputs_for(scenario_id)
        snapshot = inputs.snapshot
        intruder = sample.model_copy(
            update={
                "observation_id": "obs-chain-effect-intruder",
                "tenant_id": snapshot.tenant_id,
                "instrument_id": next(iter(inputs.observations.values())).instrument_id,
                "recorded_at": snapshot.known_at,
            }
        )
        widened = inputs.__class__(
            snapshot=snapshot.model_copy(
                update={
                    "observation_ids": sorted([*snapshot.observation_ids, intruder.observation_id])
                }
            ),
            profile=inputs.profile,
            observations={**inputs.observations, intruder.observation_id: intruder},
            coverage=inputs.coverage,
            identity_links=inputs.identity_links,
        )
        base, other = evaluate(inputs).result, evaluate(widened).result
        assert other.result == base.result, scenario_id
        assert [c.model_dump() for c in other.controls] == [
            c.model_dump() for c in base.controls
        ], scenario_id



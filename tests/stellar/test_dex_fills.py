"""DEX fills as exchange effects, apart from the movements the profiles admit.

The cases come from the SYNTHETIC recordings in ``tests/fixtures/stellar/synthetic/
dex-fills`` (generated by ``build_dex_fills.py``; nothing there exists on any network).
The real fills ``usdc-gbain6`` and ``usdc-issuer-fill`` are covered in ``test_adapter.py``.
"""


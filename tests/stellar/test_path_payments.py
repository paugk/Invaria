    assert [
        (v.account, v.direction, v.units.atoms if v.units else None) for v in legs.values()
    ] == [
        # Every leg is seen from its sender, whoever the watched account is.
        (O1, "debit", "30000000"),
        (O2, "debit", "45000000"),
        (C, "debit", "75000000"),
    ]
    check = _correspondence(store, "pp-receive-multileg")
    assert check["status"] == "corroborated"
    assert check["classic_net"] == check["sac_net"] == {A: "75000000", C: "0"}



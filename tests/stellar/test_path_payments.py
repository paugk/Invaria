def test_chain_effect_contract_rules(run: Any) -> None:
    store, _, _ = run
    classic = next(
        o.payload
        for o in store.observations()
        if isinstance(o.payload, ChainEffectPayload)
        and o.payload.representation == "classic"
        and o.payload.units is not None
    )
    assert isinstance(classic, ChainEffectPayload) and classic.units is not None
    document = classic.model_dump(mode="json")
    bad = [
        {**document, "effect_kind": "path_payment_leg"},  # a leg must come from SAC
        {**document, "representation": "sac"},  # a debit or credit comes from Classic
        {**document, "transaction": None},  # Classic keeps the transaction outcome
        {**document, "counterparty": None},
        {**document, "units": {**document["units"], "scale": 6}},
        {
            **document,
            "transaction": {
                **document["transaction"],
                "fee_charged": {"atoms": "100", "scale": 7, "unit": "USDC"},
            },
        },
    ]
    for candidate in bad:
        with pytest.raises(ValueError):
            ChainEffectPayload.model_validate(candidate)
    ChainEffectPayload.model_validate(document)
    trade = {
        "operation_type": "manage_sell_offer",
        "operation_source": B,
        "offer_id": "1",
        "sold_asset": "native",
        "sold_amount": "1",
        "bought_asset": "native",
        "bought_amount": "1",
    }
    fill = {**document, "effect_kind": "dex_fill", "path_payment": None, "transaction": None}
    ChainEffectPayload.model_validate({**fill, "exchange": trade})
    no_trade = {k: None for k in trade if k not in ("operation_type", "operation_source")}
    ChainEffectPayload.model_validate(
        {**fill, "representation": "sac", "exchange": {**trade, **no_trade}}
    )
    unresolved = {"reason": "operation_not_found", "operation_type": None}
    for candidate in [
        fill,  # a fill names its exchange
        {**fill, "exchange": {**trade, **no_trade}},  # a Classic fill carries its trade
        {**fill, "representation": "sac", "exchange": trade},  # a SAC fill does not
        {**fill, "exchange": {**trade, "sold_amount": None}},  # all trade fields or none
        {**fill, "exchange": trade, "unresolved": unresolved},
        {**fill, "effect_kind": "unresolved_movement", "unresolved": unresolved},  # SAC only
        {**fill, "effect_kind": "unresolved_movement", "representation": "sac"},  # says why
        {**document, "exchange": trade},  # a path effect is not a fill
    ]:
        with pytest.raises(ValueError):
            ChainEffectPayload.model_validate(candidate)
    ChainEffectPayload.model_validate(
        {
            **fill,
            "effect_kind": "unresolved_movement",
            "representation": "sac",
            "unresolved": unresolved,
        }
    )



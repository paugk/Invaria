def test_a_changed_leg_set_revises_the_check_and_other_assets_are_ignored(tmp_path: Path) -> None:
    store = IngestStore(tmp_path)
    horizon, rpc = _clients()
    _classic(store, horizon, rpc)
    _sac(store, horizon, rpc)
    key = (TARGET.target_id, _tx("pp-send-debit"), 0)
    before = store.current_correspondence()[key]
    assert before["status"] == "corroborated"
    leg = next(
        o for o in store.observations() if o.source.record_key == f"{_tx('pp-send-debit')}:0:sac:0"
    )
    # A leg of another asset with the same key: not this target's evidence.
    foreign = leg.model_copy(
        update={"observation_id": "obs-foreign-asset", "instrument_id": "synthetic:asset:EURX"}
    )
    assert isinstance(leg.payload, ChainEffectPayload)
    other_network = leg.model_copy(
        update={
            "observation_id": "obs-foreign-network",
            "payload": leg.payload.model_copy(
                update={"chain": leg.payload.chain.model_copy(update={"network": "stellar:pubnet"})}
            ),
        }
    )
    store.append_observations([foreign, other_network])
    _sac(store, horizon, rpc)
    assert store.current_correspondence()[key] == before
    # A second, different content for the same leg: neither copy is chosen nor summed.
    assert isinstance(leg.payload, ChainEffectPayload) and leg.payload.units is not None
    altered = leg.model_copy(
        update={
            "observation_id": "obs-altered-leg",
            "payload": leg.payload.model_copy(
                update={"units": leg.payload.units.model_copy(update={"atoms": "1"})}
            ),
        }
    )
    store.append_observations([altered])
    rerun = _sac(store, horizon, rpc)
    after = store.current_correspondence()[key]
    assert (
        after["status"] == "sac_incomplete"
        and after["evidence_sha256"] != before["evidence_sha256"]
    )
    history = [
        e for e in store.correspondence() if (e["target_id"], e["tx_hash"], e["op_index"]) == key
    ]
    assert [e["status"] for e in history] == ["corroborated", "sac_incomplete"]
    assert rerun.coverage is not None and rerun.coverage.records_quarantined == 7 + 5



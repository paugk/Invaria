def test_two_fills_in_one_operation_reconcile_in_aggregate_only(run: Any) -> None:
    store, _, _ = run
    effects = _of(store, "fill-two-offers")
    assert len(effects) == 4  # two trades and two events: none deduplicated
    check = store.current_correspondence()[(TARGET.target_id, _tx("fill-two-offers"), 0)]
    assert check["status"] == "corroborated" and check["claim"] == "aggregate_reconciliation"
    assert check["classic_gross"] == check["sac_gross"] == {"debit": "25000000", "credit": "0"}


def test_fill_conflict_keeps_both_sides_and_quarantines(run: Any) -> None:
    store, _, sac = run
    assert _status(store, "fill-conflict") == "conflict"
    assert {_payload(o).units.atoms for o in _of(store, "fill-conflict")} == {  # type: ignore[union-attr]
        "30000000",
        "40000000",
    }
    conflicts = [e for e in sac.exclusions if e.reason == "CORRESPONDENCE_CONFLICT"]
    assert len(conflicts) == 1 and all(e.quarantine for e in conflicts)


@pytest.mark.parametrize(
    ("label", "reason"),
    [
        ("unresolved-type", "unsupported_operation_type"),
        ("unresolved-not-found", "operation_not_found"),
        ("fill-incomplete", "incomplete_trade_data"),
        # A DEX operation without a trade of A: its type alone does not prove a fill.
        ("fill-sac-only", "incomplete_trade_data"),
    ],
)
def test_an_unresolved_origin_is_kept_and_satisfies_nothing(
    run: Any, label: str, reason: str
) -> None:
    store, _, sac = run
    (effect,) = _of(store, label)
    payload = _payload(effect)
    assert effect.fact_type == "chain_effect" and payload.effect_kind == "unresolved_movement"
    assert payload.unresolved is not None and payload.unresolved.reason == reason
    assert payload.account == A and payload.units is not None
    (exclusion,) = [e for e in sac.exclusions if e.locator == effect.provenance.raw_locator]
    assert exclusion.reason == "UNRESOLVED_ORIGIN" and exclusion.quarantine


def test_listed_payments_and_contract_calls_stay_movements(run: Any) -> None:
    store, _, _ = run
    for label, atoms in (("listed-payment", "9000000"), ("unlisted-invoke", "8000000")):
        movements = _of(store, label)
        assert [o.fact_type for o in movements] == ["token_movement"], label
        assert isinstance(movements[0].payload, TokenMovementPayload)
        assert movements[0].payload.units.atoms == atoms
    # A listed operation is never looked up: its classification needs no second source.
    urls = [
        json.loads(meta.read_text("utf-8"))["url"]
        for meta in (SYNTHETIC / "recordings").glob("*.json")
    ]
    assert not any(_tx("listed-payment") in url for url in urls)
    assert any(_tx("unlisted-invoke") in url for url in urls)
    # Unlisted, the contract call is still a movement but the sources disagree: quarantined.
    _, _, sac = run
    (gap,) = [e for e in sac.exclusions if e.reason == "NOT_LISTED_BY_HORIZON"]
    assert gap.quarantine and gap.locator == _of(store, "unlisted-invoke")[0].provenance.raw_locator


